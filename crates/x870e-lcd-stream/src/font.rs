//! Embedded 8x8 bitmap font for crisp, dependency-free text rendering on 720x1280 frames.

pub const FONT_WIDTH: usize = 8;
#[allow(dead_code)]
pub const FONT_HEIGHT: usize = 8;

/// Returns the 8x8 bitmap glyph representation for an ASCII character.
/// Falls back to '?' for unknown or non-ASCII characters.
pub fn get_glyph(c: char) -> &'static [u8; 8] {
    let ascii = c as usize;
    if (32..=126).contains(&ascii) {
        &BASIC_FONT[ascii - 32]
    } else {
        &BASIC_FONT[31] // '?' for unknown (ASCII 63 - 32 = 31)
    }
}

/// Renders a text string into a BGRA8888 frame buffer at the specified coordinates and scale.
pub fn draw_text_bgra(
    buffer: &mut [u8],
    stride_width: usize,
    stride_height: usize,
    x: usize,
    y: usize,
    text: &str,
    color: [u8; 4], // [B, G, R, A]
    scale: usize,
) {
    let mut cursor_x = x;
    for c in text.chars() {
        if c == '\n' {
            continue;
        }
        let glyph = get_glyph(c);
        for row in 0..8 {
            let row_byte = glyph[row];
            for col in 0..8 {
                if (row_byte >> (7 - col)) & 1 == 1 {
                    for dy in 0..scale {
                        let py = y + row * scale + dy;
                        if py >= stride_height {
                            continue;
                        }
                        for dx in 0..scale {
                            let px = cursor_x + col * scale + dx;
                            if px >= stride_width {
                                continue;
                            }
                            let offset = (py * stride_width + px) * 4;
                            if offset + 3 < buffer.len() {
                                buffer[offset] = color[0];     // B
                                buffer[offset + 1] = color[1]; // G
                                buffer[offset + 2] = color[2]; // R
                                buffer[offset + 3] = color[3]; // A
                            }
                        }
                    }
                }
            }
        }
        cursor_x += (FONT_WIDTH + 1) * scale;
    }
}

